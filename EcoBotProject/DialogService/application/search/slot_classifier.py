def _normalize_class_query(query: str, slots: dict) -> dict:
    """Классовый запрос → synonym=null + фильтры (Тип ОФФ / Подтип / Редкость).

    Работает только когда в запросе нет собственных имён: все значимые слова —
    класс или модификатор. "Баргузинский заповедник" и "даурский ёж" не трогаем.
    """
    words = re.findall(r"\w+", query.lower().replace("ё", "е"))
    groups, mods, unknown = set(), set(), []
    prev = None
    for w in words:
        if prev in _PREPOSITIONS and w not in _QUERY_STOP:
            prev = w
            continue            # слово после предлога — место, а не имя объекта
        prev = w
        if w in _QUERY_STOP or len(w) < 2:
            continue
        group = "geo" if w in _GEO_NOUNS else None
        if not group:
            group = next((g for g, stems in _CLASS_STEMS.items()
                          if any(w.startswith(s) for s in stems)), None)
        if group:
            groups.add(group)
            continue
        if any(w.startswith(s) for s in _MOD_STEMS):
            mods.add(w)
            continue
        unknown.append(w)

    if unknown or not (groups or mods):
        return slots

    props = dict(slots.get("properties") or {})
    slots["class_query"] = True   # null здесь осознанный: пользователь спросил класс
    slots["synonym"] = None

    if "geo" in groups:
        slots["object_type"] = "Географический объект"
        props.pop("Тип ОФФ", None)
        for w in words:
            if w in _SUBTYPE_BY_NOUN:
                props["Подтип объекта"] = _SUBTYPE_BY_NOUN[w]
                break
    elif "flora" in groups and "fauna" not in groups:
        slots["object_type"] = "Объект флоры и фауны"
        props["Тип ОФФ"] = "Объект флоры"
    elif "fauna" in groups and "flora" not in groups:
        slots["object_type"] = "Объект флоры и фауны"
        props["Тип ОФФ"] = "Объект фауны"
    elif groups & {"flora", "fauna"}:
        slots["object_type"] = "Объект флоры и фауны"

    if any(w.startswith(("редк", "краснокниж")) for w in mods):
        props["Редкость"] = "Редкое"
    elif any(w.startswith("эндем") for w in mods):
        props["Редкость"] = "Эндемик"

    slots["properties"] = props
    return slots


def _post_process_slots(query: str, slots: dict, valid_features: Optional[Dict[str, Set[str]]] = None) -> dict:
    """
    Детерминированные поправки к выводу LLM:
    1. Определение Услуги по ключевым маркерам запроса
    2. Fallback Тип ОФФ из ключевых слов для ОФФ без синонима
    3. Очистка Расположение относительно Байкала когда "байкал" часть синонима
    4. Fallback Расположение относительно Байкала при явном слове "Байкал"
    5. Нормализация топонима: features.location / features["Детальное расположение"] → properties["Детальное расположение"]
    6. Фильтрация галлюцинированных features по допустимому списку из БД
    """
    q_lower = query.lower()
    props = dict(slots.get("properties") or {})
    features = dict(slots.get("features") or {})
    synonym = (slots.get("synonym") or "").lower()

    # ── 0. features для разных модальностей ───────────────────────────────
    # Согласно обновленному промпту, features разрешены для "Текст" и "Изображение".
    # Для "Геоданные" они должны быть пустыми.
    if features and slots.get("modality") == "Геоданные":
        logger.info("🔍 features dropped for Геоданные modality")
        slots["features"] = {}
        features = {}
    elif features and slots.get("modality") == "Текст":
        pass

    # ── 0.5. Явный маркер карты → Геоданные ──────────────────────────────────
    # "на карте", "на карту", "по карте", "карту/карте" — однозначный сигнал
    # формата. Перекрывает даже шаг 0: features релевантны только для Изображения.
    if _GEO_MAP_RE.search(query) and slots.get("modality") != "Геоданные":
        slots["modality"] = "Геоданные"
        slots["features"] = {}

    # ── 0.7. Явный маркер изображения → Изображение ─────────────────────────
    # "покажи", "фото", "картинку" — однозначный сигнал, если нет карты и "где".
    if (
        slots.get("modality") != "Изображение"
        and not _GEO_MAP_RE.search(query)
        and _IMAGE_MARKER_RE.search(q_lower)
        and not re.search(r'\bгде\b', q_lower)
    ):
        slots["modality"] = "Изображение"

    # ── 1. Определение Услуги по маркерам ────────────────────────────────────
    if slots.get("object_type") != "Услуга":
        for marker in _SERVICE_MARKERS:
            if marker in q_lower:
                slots["object_type"] = "Услуга"
                break
            
    # ── 1.5. Классовые запросы, перечисления, топонимы ──────────────────────
    slots = _normalize_class_query(query, slots)
    props = dict(slots.get("properties") or {})
    features = dict(slots.get("features") or {})
    synonym = (slots.get("synonym") or "").lower()
    if _is_class_like_synonym(synonym):
        logger.info(f"🔍 Class-like synonym nullified: {slots.get('synonym')!r}")
        slots["synonym"] = None
        slots["class_query"] = True
        synonym = ""
    elif slots.get("synonym"):
        # Несколько объектов: оставляем ВСЕ имена, каждое дополняем до полного.
        parts = [x.strip(" .;,") for x in re.split(r",|;|\s+и\s+", str(slots["synonym"]))]
        fixed = []
        for part in [x for x in parts if x]:
            key = part.lower().replace("ё", "е")
            full = _NAME_ALIASES.get(key, part)
            if full != part:
                logger.info(f"🔍 Synonym alias: {part!r} → {full!r}")
            fixed.append(full)
        if fixed:
            slots["synonym"] = ", ".join(fixed)
            synonym = slots["synonym"].lower()

    # ── 2. Fallback Тип ОФФ (только для ОФФ, только без синонима) ────────────
    if slots.get("object_type") == "Объект флоры и фауны" and not slots.get("synonym"):
        if "Тип ОФФ" not in props:
            q_words = set(re.findall(r'\w+', q_lower))
            has_flora = bool(q_words & _FLORA_WORDS)
            has_fauna = bool(q_words & _FAUNA_WORDS)
            if has_flora and not has_fauna:
                props["Тип ОФФ"] = "Объект флоры"
            elif has_fauna and not has_flora:
                props["Тип ОФФ"] = "Объект фауны"
            # Оба → не устанавливаем (запрос о флоре И фауне одновременно)
            
    # Если пользователь просит "редкие" или "эндемики", ищем оба значения.
    if "эндем" in q_lower:
        props["Редкость"] = "Эндемик"
    elif "редк" in q_lower or "краснокниж" in q_lower:
        props["Редкость"] = "Редкое"

    # ── 3. Очистка Расположение относительно Байкала если "байкал" — часть синонима ──
    # Пример: "Байкальский музей" содержит "байкал", но это имя объекта, не озеро
    if "байкал" in synonym and "Расположение относительно Байкала" in props:
        del props["Расположение относительно Байкала"]

    # ── 4. Fallback Расположение относительно Байкала при явном упоминании Байкала ──
    if "Расположение относительно Байкала" not in props and _BAIKAL_RE.search(query) and "байкал" not in synonym:
        if _BAIKAL_NEAR_RE.search(query):
            props["Расположение относительно Байкала"] = "рядом/около Байкала"
        else:
            props["Расположение относительно Байкала"] = "в/на Байкале"

    # ── 5. Нормализация топонима → properties["Детальное расположение"] ──────
    # LLM может положить топоним в features под разными ключами
    for key in ("Детальное расположение", "location"):
        if key in features and not props.get("Детальное расположение"):
            props["Детальное расположение"] = features.pop(key)
        elif key in features:
            features.pop(key)
    if "location" in props and not props.get("Детальное расположение"):
        props["Детальное расположение"] = props.pop("location")
    elif "location" in props:
        props.pop("location")

    # ── 5.4. Недопустимые значения "Расположение относительно Байкала" ────
    # "на Ольхоне", "в горах" и т.п. — не допустимые значения, из-за них
    # фильтр по объектам даёт 0. Просто убираем, местоположение оставляем модели.
    _BAIKAL_OK = {"в/на Байкале", "рядом/около Байкала", "неизвестно"}
    baikal_val = props.get("Расположение относительно Байкала")
    if baikal_val and baikal_val not in _BAIKAL_OK:
        logger.info(f"🔍 Dropped invalid Baikal value: {baikal_val!r}")
        props.pop("Расположение относительно Байкала", None)

    # ── 5.5. Признаки, ошибочно попавшие в properties ─────────────────────
    # "нерпа зимой": модель кладёт Время года в properties → фильтр по объектам
    # даёт 0 и уходим в векторный fallback с летними фото. Переносим в features.
    if slots.get("modality") == "Изображение":
        for k in list(props):
            if k in _FEATURE_KEYS:
                features.setdefault(k, props.pop(k))
    else:
        for k in list(props):
            if k in _FEATURE_KEYS:
                props.pop(k)

    # ── 6. Фильтрация features по допустимому списку из resource_feature ──────
    # Если valid_features загружены из БД — оставляем только те признаки,
    # которые реально существуют для данной модальности в resource.features.
    # Это устраняет галлюцинации ЛЛМ типа {"Среда обитания": "Горы"} при Геоданных.
    if valid_features is not None:
        modality = slots.get("modality", "Текст")
        allowed: Set[str] = valid_features.get(modality, set())
        features = {k: v for k, v in features.items() if k.lower() in allowed}

    slots["properties"] = props
    slots["features"] = features
    return slots


class SlotResult(BaseModel):
    model_config = ConfigDict(extra='forbid')
    object_type: Optional[Literal["Объект флоры и фауны", "Географический объект", "Услуга"]] = None
    synonym: Optional[str] = None
    properties: Dict[str, Any] = Field(default_factory=dict)
    features: Dict[str, Any] = Field(default_factory=dict)
    extra: Dict[str, Any] = Field(default_factory=dict)
    modality: Literal["Текст", "Изображение", "Геоданные"] = "Текст"

    @field_validator('object_type', mode='before')
    @classmethod
    def normalize_object_type(cls, v):
        """Исправляет типичные сокращения LLM до канонического значения."""
        return _OBJECT_TYPE_ALIASES.get(v, v)


def _determine_template(slots: dict) -> Optional[str]:
    obj_type = slots.get("object_type")
    synonym = slots.get("synonym")
    properties = slots.get("properties") or {}
    features = slots.get("features") or {}
    extra = slots.get("extra") or {}
    modality = slots.get("modality", "Текст")

    feat_location = properties.get("Детальное расположение")
    baikal_rel = properties.get("Расположение относительно Байкала")
    # "Расположение относительно Байкала" ("в/на Байкале", "рядом/около Байкала") засчитывается как location
    effective_location = feat_location or (baikal_rel if baikal_rel and baikal_rel != "неизвестно" else None)

    image_features = features
    tipo_off = properties.get("Тип ОФФ")
    subtypes = properties.get("Подтип объекта")
    # служебные поля не считаются "дополнительными фильтрами"
    other_props = {k: v for k, v in properties.items() if k not in {"Тип ОФФ", "Расположение относительно Байкала", "Детальное расположение"}}

    # has_any_props: есть ли какие-то фильтры помимо базовой локации и типа
    # тип офф учитывается только при отсутствии синонима (с синонимом тип избыточен)
    if synonym:
        has_any_props = bool(other_props) or bool(extra)
    else:
        has_any_props = bool(tipo_off) or bool(other_props) or bool(extra)

    if obj_type == "Объект флоры и фауны":
        if synonym:
            if modality == "Текст":
                return "О2" if has_any_props else "О1"
            elif modality == "Изображение":
                return "О3" if image_features else "О4"
            elif modality == "Геоданные":
                # О5 — показать ареал конкретного вида в конкретном месте
                return "О5" if effective_location else "О6"
        else:
            if modality == "Геоданные" and effective_location:
                return "О11"
            if modality == "Изображение":
                # Фото категории объектов — всегда О9 (habitat опционален)
                return "О9"
            if effective_location:
                if tipo_off and not other_props and not extra:
                    return "О12"
                if has_any_props:
                    return "О8"
                return "О10"
            if has_any_props:
                return "О7"

    elif obj_type == "Географический объект":
        if synonym:
            if modality == "Геоданные":
                return "Г3"
            if effective_location:
                return "Г2"
            return "Г1"
        else:
            if subtypes and effective_location:
                return "Г5" if modality == "Геоданные" else "Г4"
            if subtypes:
                return "Г6"
            if effective_location:
                return "Г7"

    elif obj_type == "Услуга":
        if synonym:
            return "У2" if effective_location else "У1"
        if effective_location:
            return "У3"

    return None


class SlotClassifier:
    def __init__(self, provider: str = "qwen", valid_features: Optional[Dict[str, Set[str]]] = None):
        self._provider = provider
        self._valid_features = valid_features
        llm = LLMFactory.get_model(provider)
        self.parser = llm.with_structured_output(SlotResult, method="json_mode")

    def reload(self) -> None:
        provider = os.getenv("LLM_PROVIDER", self._provider)
        llm = LLMFactory.get_model(provider)
        self.parser = llm.with_structured_output(SlotResult, method="json_mode")
        self._provider = provider

    async def classify(self, query: str, prev_query: str | None = None, prev_promo: list | None = None) -> dict:
        context_parts = []

        if prev_query:
            context_parts.append(
                f"Предыдущий запрос пользователя: «{prev_query}»\n"
                f"Используй его ИСКЛЮЧИТЕЛЬНО чтобы понять на что указывают местоимения "
                f"(«он», «она», «его», «её», «нём», «ней», «там», «это», «туда» и т.п.). "
                f"Не переноси слоты из предыдущего запроса — классифицируй только текущий."
            )

        if prev_promo:
            names = "; ".join(
                f"«{item.get('name', '')}» (тип: {item.get('object_type', '')})"
                for item in prev_promo
            )
            context_parts.append(
                f"В предыдущем ответе были рекомендованы объекты: {names}\n"
                f"Если текущий запрос ссылается на один из них (через «эту», «про неё», «подробнее», «расскажи об этом» и т.п.) — "
                f"укажи его название в synonym и соответствующий object_type."
            )

        if context_parts:
            context = "\n═══ КОНТЕКСТ ДИАЛОГА ═══\n" + "\n".join(context_parts) + "\n"
        else:
            context = ""

        prompt = _get_prompt_template().format(context=context, query=query)
        logger.info(f"🔍 Classifying: '{query}'" + (f" | prev: '{prev_query}'" if prev_query else "") + (f" | promo: {[p.get('name') for p in (prev_promo or [])]}" if prev_promo else ""))
        try:
            result: SlotResult = await self.parser.ainvoke(prompt)
            raw_slots = result.model_dump()

            slots = result.model_dump()
            slots = _post_process_slots(query, slots, self._valid_features)
            slots["template"] = _determine_template(slots)
            slots["modality_ambiguous"] = _detect_ambiguity(query, slots["modality"])
            slots["_debug_llm_raw"] = raw_slots
            logger.info(f"🔍 Raw LLM slots: synonym={slots.get('synonym')!r} object_type={slots.get('object_type')!r} modality={slots.get('modality')!r} features={slots.get('features')}")
            return slots
        except Exception as e:
            logger.error(f"SlotClassifier error: {e}")
            return {
                "object_type": None,
                "synonym": None,
                "properties": {},
                "features": {},
                "extra": {},
                "modality": "Текст",
                "modality_ambiguous": False,
                "template": None,
                "error": str(e)
            }
